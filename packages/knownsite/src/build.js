// `knownsite build`: run after the framework build, over the static output directory.
// Writes sitemap.xml, llms.txt, robots.txt, JSON-LD, the Knownsite manifest, signed content records,
// the deploy change list, and the IndexNow key file. SPEC.md §3, §5, §6.
import { createHash, randomUUID } from 'node:crypto';
import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { findHtmlFiles, fileToPath, parseHtml, summarize } from './scan.js';
import { signObject, publicKeyFor } from './sign.js';
import { SHELL_FILE } from './prerender.js';

export const PROTOCOL_VERSION = '0.1';
const MARK = 'generated by knownsite';
export const PATHS = {
  manifest: '.well-known/discovery.json',
  records: '.well-known/discovery/records.jsonl',
  lastDeploy: '.well-known/discovery/last-deploy.json',
};

const xmlEscape = (s) =>
  s.replace(/[<>&'"]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', "'": '&apos;', '"': '&quot;' })[c]);
const stripSlash = (u) => (u.length > 1 && u.endsWith('/') ? u.slice(0, -1) : u);

function isExcluded(urlPath, patterns) {
  return patterns.some((p) => (p.endsWith('*') ? urlPath.startsWith(p.slice(0, -1)) : urlPath === p));
}

export function parseRecords(jsonl) {
  return jsonl
    .split('\n')
    .filter((l) => l.trim())
    .map((l) => JSON.parse(l));
}

/** Records currently live on the site (the previous deploy). Empty on first deploy or failure. */
export async function fetchPreviousRecords(site, fetchImpl = fetch) {
  try {
    const res = await fetchImpl(`${site}/${PATHS.records}`, { signal: AbortSignal.timeout(10_000) });
    if (!res.ok) return [];
    return parseRecords(await res.text());
  } catch {
    return [];
  }
}

/** Same text, title and summary: a title or description change is an update too (it changes search results). */
export function sameContent(a, b) {
  return a.hash === b.hash && (a.title ?? '') === (b.title ?? '') && (a.summary ?? '') === (b.summary ?? '');
}

export function diffRecords(prev, next) {
  const before = new Map(prev.map((r) => [r.url, r]));
  const after = new Map(next.map((r) => [r.url, r]));
  return {
    added: next.filter((r) => !before.has(r.url)).map((r) => r.url),
    updated: next.filter((r) => before.has(r.url) && !sameContent(before.get(r.url), r)).map((r) => r.url),
    removed: prev.filter((r) => !after.has(r.url)).map((r) => r.url),
  };
}

function jsonLdFor(config, page) {
  const data =
    page.path === '/'
      ? { '@context': 'https://schema.org', '@type': 'WebSite', name: config.name || page.title, url: page.url,
          description: page.summary || undefined }
      : { '@context': 'https://schema.org', '@type': 'WebPage', name: page.title, url: page.url,
          description: page.summary || undefined, inLanguage: page.lang || undefined,
          dateModified: page.modified, isPartOf: { '@type': 'WebSite', url: config.site } };
  return `<script type="application/ld+json">${JSON.stringify(data).replace(/</g, '\\u003c')}</script>`;
}

export function renderSitemap(records) {
  const urls = records
    .map((r) => `  <url><loc>${xmlEscape(r.url)}</loc><lastmod>${r.modified}</lastmod></url>`)
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- ${MARK} -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

export function renderLlmsTxt(config, records) {
  const home = records.find((r) => r.url === `${config.site}/`);
  const name = config.name || home?.title || new URL(config.site).hostname;
  const description = config.description || home?.summary || '';
  const lines = [`# ${name}`, ''];
  if (description) lines.push(`> ${description}`, '');
  lines.push('## Pages', '');
  for (const r of records) lines.push(`- [${r.title || r.url}](${r.url})${r.summary ? `: ${r.summary}` : ''}`);
  lines.push('', `<!-- ${MARK} -->`, '');
  return lines.join('\n');
}

async function readIfExists(file) {
  try {
    return await readFile(file, 'utf8');
  } catch {
    return null;
  }
}

/** Write unless the file exists and was authored by someone else (e.g. the framework's own sitemap). */
async function writeOwned(file, content) {
  const existing = await readIfExists(file);
  if (existing !== null && !existing.includes(MARK)) return false;
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content);
  return true;
}

/** Host settings that would silently drop /.well-known/ on upload. */
export async function hostingWarnings(cwd) {
  const warnings = [];
  const firebase = await readIfExists(path.join(cwd, 'firebase.json'));
  if (firebase) {
    try {
      const hosting = [JSON.parse(firebase).hosting].flat().filter(Boolean);
      if (hosting.some((h) => (h.ignore ?? []).some((g) => g === '**/.*' || g === '.*' || g === '**/.**'))) {
        warnings.push('firebase.json "hosting.ignore" skips dotfiles ("**/.*"), so /.well-known/ will not be uploaded. Remove that entry.');
      }
    } catch {
      // not our file to validate
    }
  }
  return warnings;
}

const isDir = async (p) => (await stat(p).catch(() => null))?.isDirectory() ?? false;
const isFile = async (p) => (await stat(p).catch(() => null))?.isFile() ?? false;

/**
 * Where the built pages are and where Knownsite's files go.
 * - static: a static export (out/, dist/, public HTML): read and write the same directory.
 * - next-server: `next build` without `output: 'export'`. Prerendered pages are read from
 *   .next/server/{app,pages}; Knownsite's files are written to public/, which Next.js and Vercel
 *   serve as static files. Pages rendered per request have no HTML at build time and are not
 *   recorded; routes the app generates itself (app/sitemap.ts, app/robots.ts, ...) are left alone.
 */
export async function resolveLayout(cwd, config) {
  const outDir = path.resolve(cwd, config.outDir);
  if (await isDir(outDir)) {
    return { mode: 'static', htmlRoots: [outDir], writeDir: outDir, injectJsonLd: config.jsonld, appRoutes: new Set(), dynamicRoutes: [] };
  }
  const nextDir = path.resolve(cwd, config.nextDir ?? '.next');
  if (await isFile(path.join(nextDir, 'BUILD_ID'))) {
    const htmlRoots = [];
    for (const d of ['app', 'pages']) if (await isDir(path.join(nextDir, 'server', d))) htmlRoots.push(path.join(nextDir, 'server', d));
    const appRoutes = new Set();
    const pageRoutes = [];
    const manifest = await readIfExists(path.join(nextDir, 'server', 'app-paths-manifest.json'));
    for (const key of Object.keys(manifest ? JSON.parse(manifest) : {})) {
      const route = key.replace(/\/(page|route)$/, '') || '/';
      // Route groups "(marketing)" and parallel slots "@modal" don't appear in URLs.
      const url = route.split('/').filter((s) => !/^\(.*\)$/.test(s) && !s.startsWith('@')).join('/') || '/';
      if (key.endsWith('/route')) appRoutes.add(url);
      else if (!url.split('/').some((s) => s.startsWith('_'))) pageRoutes.push(url);
    }
    return { mode: 'next-server', htmlRoots, writeDir: path.resolve(cwd, config.publicDir ?? 'public'),
      injectJsonLd: false, appRoutes, pageRoutes };
  }
  throw new Error(`No build output found: neither ${outDir} nor a Next.js build in ${nextDir}. `
    + 'Run your framework build first, or set "outDir".');
}

/**
 * @param {object} opts
 * @param {string} opts.cwd
 * @param {object} opts.config        from loadConfig()
 * @param {string|null} opts.privateKey  base64url PKCS#8; null = unsigned (Level 1)
 * @param {object[]} [opts.previousRecords]  defaults to fetching the live site's records
 * @param {Date} [opts.now]
 */
export async function build({ cwd, config, privateKey, previousRecords, now = new Date(), fetchImpl = fetch }) {
  const layout = await resolveLayout(cwd, config);
  const outDir = layout.writeDir;

  const kid = config.keys[0]?.kid;
  if (privateKey) {
    if (!kid) throw new Error('A private key is set but knownsite.config.json has no "keys". Run `knownsite init`.');
    if (publicKeyFor(privateKey) !== config.keys[0].pub) {
      throw new Error(`Private key does not match public key "${kid}" in knownsite.config.json.`);
    }
  }

  // Only records on this site's own origin: after a domain move the old records name the old host,
  // and those URLs are not this site's to add, update or remove.
  const sameOrigin = (u) => { try { return new URL(u).origin === config.site; } catch { return false; } };
  const prev = (previousRecords ?? (await fetchPreviousRecords(config.site, fetchImpl))).filter((r) => sameOrigin(r.url));
  const prevByUrl = new Map(prev.map((r) => [r.url, r]));
  const timestamp = now.toISOString().replace(/\.\d{3}Z$/, 'Z');

  const pages = [];
  const skipped = [];
  const seen = new Set();
  const htmlFiles = [];
  for (const root of layout.htmlRoots) for (const rel of await findHtmlFiles(root)) htmlFiles.push({ root, rel });
  for (const { root, rel } of htmlFiles) {
    // Next.js internals (_not-found, _global-error, _app, _document, _error) are not pages.
    if (layout.mode === 'next-server' && rel.split('/').some((s) => s.startsWith('_'))) continue;
    // The SPA shell `knownsite prerender` keeps for the host's fallback is not a page.
    if (rel === SHELL_FILE) continue;
    const urlPath = fileToPath(rel);
    if (seen.has(urlPath) || isExcluded(urlPath, config.exclude)) continue;
    seen.add(urlPath);
    const file = path.join(root, rel);
    const html = await readFile(file, 'utf8');
    const meta = parseHtml(html);
    const url = urlPath === '/' ? `${config.site}/` : `${config.site}${urlPath}`;
    if (meta.noindex) { skipped.push({ url, reason: 'noindex' }); continue; }
    if (meta.canonical) {
      const canonical = new URL(meta.canonical, url).href;
      if (stripSlash(canonical) !== stripSlash(url)) { skipped.push({ url, reason: `canonical is ${canonical}` }); continue; }
    }
    const hash = `sha256-${createHash('sha256').update(meta.text).digest('base64')}`;
    const old = prevByUrl.get(url);
    const page = { file, html, meta, path: urlPath, url, hash,
      title: meta.title, summary: summarize(meta.description, meta.text), lang: meta.lang };
    pages.push({ ...page, modified: old && sameContent(old, page) ? old.modified : timestamp });
  }
  pages.sort((a, b) => a.url.localeCompare(b.url));

  // Structured data: only where the page has none of its own. Static output only: in Next.js server
  // mode the HTML is served from .next and regenerated, so add JSON-LD in your layout instead.
  let jsonLdInjected = 0;
  const jsonLdMissing = layout.injectJsonLd ? 0 : pages.filter((p) => !p.meta.hasJsonLd).length;
  if (layout.injectJsonLd) {
    for (const p of pages) {
      if (p.meta.hasJsonLd || !/<\/head>/i.test(p.html)) continue;
      await writeFile(p.file, p.html.replace(/<\/head>/i, `${jsonLdFor(config, p)}</head>`));
      jsonLdInjected++;
    }
  }

  const records = pages.map((p) => {
    const rec = { url: p.url, title: p.title, summary: p.summary, lang: p.lang || undefined, modified: p.modified, hash: p.hash };
    return privateKey ? signObject(rec, privateKey, kid) : rec;
  });

  const changes = diffRecords(prev, records);
  const deploy = {
    id: process.env.VERCEL_DEPLOYMENT_ID || process.env.VERCEL_GIT_COMMIT_SHA || randomUUID(),
    at: timestamp,
  };
  const lastDeploy = { knownsite: PROTOCOL_VERSION, site: config.site, deploy, changes };

  const at = (p) => path.join(outDir, p);
  const written = [];
  // Files the app already serves from its own routes (app/sitemap.ts etc.) are its to keep.
  const own = (p) => layout.appRoutes.has(p);
  if (!own('/sitemap.xml') && await writeOwned(at('sitemap.xml'), renderSitemap(records))) written.push('sitemap.xml');
  if (!own('/llms.txt') && await writeOwned(at('llms.txt'), renderLlmsTxt(config, records))) written.push('llms.txt');

  const robots = own('/robots.txt') ? '' : await readIfExists(at('robots.txt'));
  const sitemapUrl = `${config.site}/sitemap.xml`;
  if (own('/robots.txt')) {
    // generated by the app; we can't edit it
  } else if (robots === null) {
    await writeFile(at('robots.txt'), `# ${MARK}\nUser-agent: *\nAllow: /\n\nSitemap: ${sitemapUrl}\n`);
    written.push('robots.txt');
  } else if (!/^sitemap:/im.test(robots)) {
    await writeFile(at('robots.txt'), `${robots.trimEnd()}\n\nSitemap: ${sitemapUrl}\n`);
    written.push('robots.txt (added Sitemap line)');
  }

  const manifest = {
    knownsite: PROTOCOL_VERSION,
    site: config.site,
    keys: config.keys,
    sitemap: sitemapUrl,
    summary: `${config.site}/llms.txt`,
    records: `${config.site}/${PATHS.records}`,
    terms: config.terms,
    indexnow: config.indexnow?.key ? `${config.site}/${config.indexnow.key}.txt` : undefined,
  };
  await mkdir(path.dirname(at(PATHS.records)), { recursive: true });
  await writeFile(at(PATHS.manifest), `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(at(PATHS.records), records.map((r) => JSON.stringify(r)).join('\n') + '\n');
  await writeFile(at(PATHS.lastDeploy), `${JSON.stringify(lastDeploy, null, 2)}\n`);
  written.push(PATHS.manifest, PATHS.records, PATHS.lastDeploy);

  if (config.indexnow?.key) {
    await writeFile(at(`${config.indexnow.key}.txt`), config.indexnow.key);
    written.push(`${config.indexnow.key}.txt`);
  }

  // Server mode: page routes with no prerendered HTML render per request; they can't be recorded yet.
  const perRequest = layout.mode === 'next-server'
    ? (layout.pageRoutes ?? []).filter((r) => !r.includes('[') && !seen.has(r) && !isExcluded(r, config.exclude))
    : [];

  return { mode: layout.mode, outDir, records, changes, deploy, skipped, written, jsonLdInjected, jsonLdMissing,
    perRequest, appRoutes: [...layout.appRoutes].filter((r) => ['/sitemap.xml', '/robots.txt', '/llms.txt'].includes(r)),
    signed: Boolean(privateKey), warnings: await hostingWarnings(cwd) };
}
