'use client';

import { useEffect, useState } from 'react';

type Manifest = { knownsite: string; site: string; keys: { kid: string }[]; terms: Record<string, string> };
type LastDeploy = { deploy: { id: string; at: string }; changes: Record<'added' | 'updated' | 'removed', string[]> };
type ContentRecord = { url: string; title: string; modified: string; hash: string; sig?: string };

const FILES = [
  ['/.well-known/discovery.json', 'Manifest'],
  ['/.well-known/discovery/records.jsonl', 'Content records'],
  ['/.well-known/discovery/last-deploy.json', 'Latest deploy'],
  ['/sitemap.xml', 'Sitemap'],
  ['/llms.txt', 'AI summary'],
  ['/robots.txt', 'robots.txt'],
];

export default function Report() {
  const [manifest, setManifest] = useState<Manifest | null>(null);
  const [last, setLast] = useState<LastDeploy | null>(null);
  const [records, setRecords] = useState<ContentRecord[]>([]);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const get = (p: string) => fetch(p, { cache: 'no-store' }).then((r) => (r.ok ? r.text() : Promise.reject(p)));
    Promise.all([get(FILES[0][0]), get(FILES[2][0]), get(FILES[1][0])])
      .then(([m, l, r]) => {
        setManifest(JSON.parse(m));
        setLast(JSON.parse(l));
        setRecords(r.split('\n').filter(Boolean).map((line) => JSON.parse(line)));
      })
      .catch((p) => setError(`Could not load ${p}. Discovery files are generated by \`knownsite build\`; they are not available in \`next dev\`.`));
  }, []);

  if (error) return <p className="bad">{error}</p>;
  if (!manifest || !last) return <p className="muted">Loading…</p>;

  const { added, updated, removed } = last.changes;
  return (
    <>
      <div className="card">
        <p style={{ marginTop: 0 }}><strong>Protocol</strong> Knownsite {manifest.knownsite} ·{' '}
          {manifest.keys.length ? <span className="ok">signed (key {manifest.keys[0].kid})</span> : <span className="muted">unsigned</span>}</p>
        <p><strong>Usage terms</strong> {Object.entries(manifest.terms).map(([k, v]) => `${k}: ${v}`).join(' · ')}</p>
        <p style={{ marginBottom: 0 }}><strong>Latest deploy</strong> {new Date(last.deploy.at).toLocaleString()} —{' '}
          {added.length} added, {updated.length} updated, {removed.length} removed</p>
      </div>

      {added.length + updated.length + removed.length > 0 && (
        <>
          <h2>Changed in the latest deploy</h2>
          <table>
            <tbody>
              {(['added', 'updated', 'removed'] as const).flatMap((kind) =>
                last.changes[kind].map((url) => (
                  <tr key={kind + url}><td>{kind}</td><td className="url">{url}</td></tr>
                )),
              )}
            </tbody>
          </table>
        </>
      )}

      <h2>Content records ({records.length})</h2>
      <table>
        <thead><tr><th>Page</th><th>Modified</th><th>Signed</th></tr></thead>
        <tbody>
          {records.map((r) => (
            <tr key={r.url}>
              <td className="url"><a href={r.url}>{r.title || r.url}</a></td>
              <td>{r.modified.slice(0, 10)}</td>
              <td>{r.sig ? <span className="ok">✓</span> : <span className="muted">—</span>}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <h2>Published files</h2>
      <ul>{FILES.map(([href, label]) => <li key={href}><a href={href}>{label}</a> <code>{href}</code></li>)}</ul>
    </>
  );
}
